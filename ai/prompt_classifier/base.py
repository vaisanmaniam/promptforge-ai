from abc import ABC, abstractmethod
from typing import Any, Dict
from pydantic import BaseModel, Field


class ClassificationResult(BaseModel):
    """Result payload from prompt task classification."""
    predicted_category: str = Field(description="Predicted TaskCategory name")
    confidence: float = Field(ge=0.0, le=1.0, description="Confidence score [0.0, 1.0]")
    probabilities: Dict[str, float] = Field(description="Probability distribution across all categories")
    model_name: str = Field(description="Name or identifier of the classifier")
    model_version: str = Field(description="Version of the model artifact or rule set")
    method: str = Field(description="'ml_model', 'rule_based_fallback', or 'untrained_baseline'")
    is_baseline: bool = Field(description="True if result was generated by a baseline heuristic")


class BasePromptClassifier(ABC):
    """Abstract interface for PromptForge AI task classifiers."""

    @abstractmethod
    def predict(self, prompt: str) -> ClassificationResult:
        """Classify a single prompt string into a TaskCategory."""
        pass

    @abstractmethod
    def predict_proba(self, prompt: str) -> Dict[str, float]:
        """Compute probability distribution over all supported categories."""
        pass

    @abstractmethod
    def get_metadata(self) -> Dict[str, Any]:
        """Return model metadata, hyperparameters, and provenance."""
        pass
